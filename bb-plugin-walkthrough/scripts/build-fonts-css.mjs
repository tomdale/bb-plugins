// Regenerates assets/newsreader.css from the @fontsource-variable/newsreader
// package (SIL OFL 1.1; license text in assets/OFL-Newsreader.txt).
// `bb plugin build` has no loader for font files, so the Latin subset is
// inlined as data URLs.
import { readFileSync, writeFileSync } from "node:fs";

const files = new URL("../node_modules/@fontsource-variable/newsreader/files/", import.meta.url);
const range = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";
const face = (style) => {
  const data = readFileSync(new URL(`newsreader-latin-wght-${style}.woff2`, files)).toString("base64");
  return `@font-face{font-family:"Newsreader Variable";font-style:${style};font-display:swap;font-weight:200 800;src:url(data:font/woff2;base64,${data}) format("woff2-variations");unicode-range:${range}}\n`;
};
writeFileSync(new URL("../assets/newsreader.css", import.meta.url), `/* Generated by scripts/build-fonts-css.mjs. Newsreader, SIL OFL 1.1. */\n${face("normal")}${face("italic")}`);
