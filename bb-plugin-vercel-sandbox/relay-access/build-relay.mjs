import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const sshBuild = await build({
  stdin: { contents: 'import ssh2 from "ssh2"; export default ssh2;', resolveDir: process.cwd() },
  bundle: true, platform: 'node', format: 'esm', target: 'node22', write: false, minify: true, legalComments: 'inline',
  plugins: [{ name: 'node-crypto-only', setup(builder) {
    builder.onResolve({ filter: /^(?:cpu-features|\.\/crypto\/build\/Release\/sshcrypto\.node)$/ }, () => ({ path: 'native-acceleration', namespace: 'disabled-native' }));
    builder.onLoad({ filter: /.*/, namespace: 'disabled-native' }, () => ({ contents: 'throw new Error("Native SSH acceleration disabled");', loader: 'js' }));
  } }],
  banner: { js: 'import {createRequire} from "node:module";const require=createRequire(import.meta.url),__filename=import.meta.filename,__dirname=import.meta.dirname;' },
});
const sshLicenses = await Promise.all(['ssh2', 'asn1', 'bcrypt-pbkdf', 'safer-buffer', 'tweetnacl'].map(async name => `${name}\n${await readFile(`node_modules/${name}/LICENSE`, 'utf8')}`));
const sshSource = `// Generated by relay-access/build-relay.mjs; standard ssh2 using Node crypto.\n${sshBuild.outputFiles[0].text}\n/* Third-party notices\n${sshLicenses.join('\n\n').replaceAll('*/', '* /')}\n*/\n`;
const sshPath = 'relay-access/ssh2-runtime.js';
if (process.argv.includes('--check')) {
  if (await readFile(sshPath, 'utf8') !== sshSource) throw new Error('SSH runtime does not match the pinned library');
} else await writeFile(sshPath, sshSource);
const result = await build({
  entryPoints: ['relay-access/relay-main.ts'], bundle: true, platform: 'node', format: 'esm', target: 'node22',
  write: false, minify: true, legalComments: 'inline', metafile: true,
  banner: { js: 'import {createRequire} from "node:module";const require=createRequire(import.meta.url),__filename=import.meta.filename,__dirname=import.meta.dirname;' },
});
const licenses = await Promise.all(['ssh2', 'ws', 'asn1', 'bcrypt-pbkdf', 'safer-buffer', 'tweetnacl'].map(async name =>
  `${name}\n${await readFile(`node_modules/${name}/LICENSE`, 'utf8')}`));
const source = `${result.outputFiles[0].text}\n/* Third-party notices\n${licenses.join('\n\n').replaceAll('*/', '* /')}\n*/\n`;
const sha256 = createHash('sha256').update(source).digest('hex');
const lockSha256 = createHash('sha256').update(await readFile('package-lock.json')).digest('hex');
const inputs = [...new Set([...Object.keys(result.metafile.inputs).filter(path => !path.startsWith('node_modules/')), 'relay-access/grants.ts', 'package.json', 'package-lock.json', '.npmrc', '.prototools', 'relay-access/build.mjs', 'relay-access/build-relay.mjs'])].sort();
const sourceSha256 = Object.fromEntries(await Promise.all(inputs.map(async path => [path, createHash('sha256').update(await readFile(path)).digest('hex')])));
const output = `// Generated by bb-plugin-vercel-sandbox/relay-access/build-relay.mjs from lockfile-verified dependencies.\nexport const relayArtifact = ${JSON.stringify({ sha256, lockSha256, sourceSha256, source })} as const;\n`;
const path = 'relay-artifact.ts';
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Relay artifact does not match source and lockfile');
} else await writeFile(path, output);
console.log(`Relay artifact SHA-256 ${sha256} (${Buffer.byteLength(source)} bytes)`);
