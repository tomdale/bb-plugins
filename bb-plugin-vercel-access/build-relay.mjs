import { build } from 'esbuild-wasm';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
const result = await build({
  entryPoints: ['relay-main.ts'], bundle: true, platform: 'node', format: 'esm', target: 'node22',
  write: false, minify: true, legalComments: 'inline', metafile: true,
  banner: { js: 'import {createRequire} from "node:module";const require=createRequire(import.meta.url),__filename=import.meta.filename,__dirname=import.meta.dirname;' },
  external: ['cpu-features', './crypto/build/Release/sshcrypto.node'],
});
const licenses = await Promise.all(['ssh2', 'ws', 'asn1', 'bcrypt-pbkdf', 'safer-buffer', 'tweetnacl'].map(async name =>
  `${name}\n${await readFile(`node_modules/${name}/LICENSE`, 'utf8')}`));
const source = `${result.outputFiles[0].text}\n/* Third-party notices\n${licenses.join('\n\n').replaceAll('*/', '* /')}\n*/\n`;
const sha256 = createHash('sha256').update(source).digest('hex');
const lockSha256 = createHash('sha256').update(await readFile('package-lock.json')).digest('hex');
const inputs = [...new Set([...Object.keys(result.metafile.inputs).filter(path => !path.startsWith('node_modules/')), 'grants.ts', 'package.json', 'package-lock.json', '.npmrc', '.prototools', 'build.mjs', 'build-relay.mjs'])].sort();
const sourceSha256 = Object.fromEntries(await Promise.all(inputs.map(async path => [path, createHash('sha256').update(await readFile(path)).digest('hex')])));
const output = `// Generated by bb-plugin-vercel-access/build-relay.mjs from lockfile-verified dependencies.\nexport const relayArtifact = ${JSON.stringify({ sha256, lockSha256, sourceSha256, source })} as const;\n`;
const path = '../bb-plugin-vercel-sandbox/relay-artifact.ts';
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Relay artifact does not match source and lockfile');
} else await writeFile(path, output);
console.log(`Relay artifact SHA-256 ${sha256} (${Buffer.byteLength(source)} bytes)`);
